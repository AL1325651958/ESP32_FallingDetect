"""Export and evaluate optional mixed INT8 inference without replacing float weights.

Weights use symmetric per-output INT8, matrix inputs symmetric dynamic INT8,
and dot products int32. Biases, features, LSTM states/nonlinearities stay float.
"""
from __future__ import annotations

import argparse
import ctypes as ct
import hashlib
import json
import subprocess
from pathlib import Path

import numpy as np

from train_physics_fall import (ROOT, WINDOW, PROJECT, LOCAL, HIDDEN, DENSE,
    MIN_VALID, GAP_MIN, GAP_MAX, SCALE, FEATURE_VERSION, features,
    load, assign_splits, class_windows, metrics)
from evaluate_dropout_fall import disconnect
from verify_physics_fall import State, Result

SOURCE = ROOT/'NN/artifacts/physics_fall'
OUT = ROOT/'NN/artifacts/physics_fall_int8'
MATRICES = ('spatial.weight', 'local.weight', 'lstm.weight_ih_l0',
            'lstm.weight_hh_l0', 'head.weight', 'out.weight')


def quantize_rows(weight):
    weight = np.asarray(weight, np.float32)
    peak = np.abs(weight).max(axis=1)
    scale = np.where(peak > 0, peak/np.float32(127), np.float32(1))
    inverse = np.ones_like(peak)
    np.divide(np.float32(127), peak, out=inverse, where=peak > 0)
    values = weight*inverse[:, None]
    q = np.clip(np.copysign(np.floor(np.abs(values)+np.float32(.5)), values), -127, 127).astype(np.int8)
    return q, scale.astype(np.float32)


def quantize_activation(values):
    values = np.asarray(values, np.float32)
    peak = np.abs(values).max()
    if peak == 0:
        return np.zeros(values.shape, np.int8), np.float32(0)
    v = values*(np.float32(127)/peak)
    q = np.clip(np.copysign(np.floor(np.abs(v)+np.float32(.5)), v), -127, 127).astype(np.int8)
    return q, np.float32(peak/np.float32(127))


def quantized_weights(weights):
    result = {k: v.copy() for k, v in weights.items() if not k.startswith('velocity.')}
    for name in MATRICES:
        result[name], result[name+'.scale'] = quantize_rows(weights[name])
    return result


def matvec(name, values, q):
    x, scale = quantize_activation(values)
    accum = q[name].astype(np.int32)@x.astype(np.int32)
    return accum.astype(np.float32)*(q[name+'.scale']*scale)


def quantized_predict(raw, q):
    h = np.zeros(HIDDEN, np.float32)
    cell = h.copy()
    maximum = np.full(HIDDEN, -np.inf, np.float32)
    sigmoid = lambda x: np.float32(1)/(np.float32(1)+np.exp(-np.clip(x, -80, 80)))
    for frame in features(raw):
        spatial = np.maximum(q['spatial.bias']+matvec('spatial.weight', frame[:128], q), 0)
        local = np.maximum(q['local.bias']+matvec('local.weight', frame[128:320], q), 0)
        projected = np.r_[spatial, local, frame[320:]]
        gates = q['lstm.bias_ih_l0']+q['lstm.bias_hh_l0']
        gates = gates+matvec('lstm.weight_ih_l0', projected, q)
        gates = gates+matvec('lstm.weight_hh_l0', h, q)
        i, f, n, o = np.split(gates, 4)
        cell = sigmoid(f)*cell+sigmoid(i)*np.tanh(n)
        h = sigmoid(o)*np.tanh(cell)
        maximum = np.maximum(maximum, h)
    dense = np.maximum(q['head.bias']+matvec('head.weight', np.r_[h, maximum], q), 0)
    logits = q['out.bias']+matvec('out.weight', dense, q)
    exp = np.exp(logits-logits.max())
    return exp/exp.sum()


def export_header(q, raw, lengths, probabilities, destination):
    def array(name, value, typ='float', storage=True):
        a = np.asarray(value).reshape(-1)
        tokens = [f'{float(v):.9e}f' if typ == 'float' else str(int(v)) for v in a]
        placement = 'FALL_WEIGHT_STORAGE ' if storage else ''
        body = ',\n    '.join(', '.join(tokens[i:i+8]) for i in range(0, len(a), 8))
        return f'static const {typ} {placement}{name}[{len(a)}] = {{\n    {body}\n}};\n'
    text = '// Generated by NN/quantize_physics_fall.py; mixed INT8, not full integer.\n#pragma once\n#include <stdint.h>\n'
    text += '#ifdef ESP_PLATFORM\n#include "esp_attr.h"\n#define FALL_WEIGHT_STORAGE DRAM_ATTR\n#else\n#define FALL_WEIGHT_STORAGE\n#endif\n'
    for k, v in dict(WINDOW=WINDOW, PROJECT=PROJECT, LOCAL=LOCAL, HIDDEN=HIDDEN,
            DENSE=DENSE, MIN_VALID=MIN_VALID, GAP_MIN_MS=GAP_MIN, GAP_MAX_MS=GAP_MAX).items():
        text += f'#define FALL_{k} {v}\n'
    text += f'#define FALL_DISTANCE_SCALE {SCALE:.1f}f\n#define FALL_FEATURE_VERSION {FEATURE_VERSION}\n'
    for name, value in q.items():
        text += array('fall_'+name.replace('.', '_'), value, 'int8_t' if name in MATRICES else 'float')
    text += '#define FALL_SELF_TEST_COUNT 3\n'
    text += array('fall_test_raw', raw[:3], 'int16_t', False)
    text += array('fall_test_lengths', lengths[:3], 'uint8_t', False)
    text += array('fall_test_probability', probabilities[:3], storage=False)
    destination.write_text(text, encoding='utf-8')


def compile_library(out, quantized):
    destination = out/('int8_classifier.dll' if quantized else 'float_classifier.dll')
    command = ['gcc', '-O3', '-Wall', '-Wextra', '-Werror', '-std=c11', '-shared',
        f'-DFALL_USE_INT8={int(quantized)}', '-I', str(ROOT/'main'),
        str(ROOT/'main/fall_classifier.c'), str(ROOT/'tests/fall_test_bridge.c'),
        '-o', str(destination), '-lm']
    subprocess.run(command, check=True)
    lib = ct.CDLL(str(destination))
    lib.fall_predict_sequence.argtypes = [ct.c_void_p, ct.c_uint, ct.c_void_p]
    lib.fall_predict_sequence.restype = ct.c_float
    lib.fall_self_test.argtypes = [ct.POINTER(ct.c_float)]
    lib.fall_self_test.restype = ct.c_bool
    lib.fall_reset.argtypes = [ct.POINTER(State)]
    lib.fall_push.argtypes = [ct.POINTER(State), ct.c_void_p, ct.c_uint32, ct.POINTER(Result)]
    return lib


def predict(lib, clips):
    probabilities = []
    for raw in clips:
        raw = np.ascontiguousarray(raw, dtype=np.int16)
        result = (ct.c_float*3)()
        lib.fall_predict_sequence(raw.ctypes.data, len(raw), result)
        p = np.array(result, np.float32)
        assert np.isfinite(p).all() and np.isclose(p.sum(), 1, atol=1e-6)
        probabilities.append(p)
    return np.array(probabilities, np.float32)


def stream_comparison(records, float_lib, int8_lib):
    updates = reused = raw_changes = stable_changes = threshold_changes = 0
    max_error = 0.0
    for record in records:
        states, results = [State(), State()], [Result(), Result()]
        for lib, state in zip((float_lib, int8_lib), states):
            lib.fall_reset(ct.byref(state))
        for frame, timestamp in zip(record['raw'], record['times']):
            for lib, state, result in zip((float_lib, int8_lib), states, results):
                lib.fall_push(ct.byref(state), frame.ctypes.data, int(timestamp)&0xffffffff, ct.byref(result))
            a, b = results
            assert a.buffered == b.buffered and a.updated == b.updated and a.valid == b.valid
            if a.buffered == WINDOW:
                updates += int(a.updated)
                reused += int(not a.updated)
                difference = float(np.abs(np.array(a.p)-np.array(b.p)).max())
                max_error = max(max_error, difference)
                raw_changes += a.raw != b.raw
                stable_changes += a.stable != b.stable
                threshold_changes += (a.p[1] >= .8) != (b.p[1] >= .8) or (a.p[1] <= .3) != (b.p[1] <= .3)
            else:
                assert a.raw == b.raw and a.stable == b.stable
    return dict(new_inference_updates=updates, reused_frames=reused,
        max_probability_change=max_error, raw_class_changes=raw_changes,
        stable_class_changes=stable_changes, fall_threshold_band_changes=threshold_changes,
        limitation='Replay of available source recordings, including training; not independent event validation.')


def edge_checks(lib):
    state, result = State(), Result()
    lib.fall_reset(ct.byref(state))
    frame = np.full(64, 1200, np.int16)
    for t in range(WINDOW+5):
        lib.fall_push(ct.byref(state), frame.ctypes.data, (0xffffff00+t*100)&0xffffffff, ct.byref(result))
        assert result.buffered == min(t+1, WINDOW)
    assert result.raw in range(3)
    # A discontinuous timestamp resets the rolling window.
    lib.fall_push(ct.byref(state), frame.ctypes.data, 10000, ct.byref(result))
    assert result.buffered == 1 and result.raw == -1
    frame[:] = -1
    lib.fall_push(ct.byref(state), frame.ctypes.data, 10100, ct.byref(result))
    assert result.raw == result.stable == 3 and result.buffered == 0
    frame[:3] = 1000
    lib.fall_push(ct.byref(state), frame.ctypes.data, 10200, ct.byref(result))
    assert result.raw == 3 and result.stable == 3 and result.buffered == 0
    frame[:] = 1200
    lib.fall_push(ct.byref(state), frame.ctypes.data, 10300, ct.byref(result))
    assert result.buffered == 1 and result.raw == -1
    return ['24-frame warmup', 'ring wrap', 'uint32 timer wrap', 'gap reset',
            'zero-valid observation lost', 'too few valid zones remain unknown', 'nonempty reacquisition']


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, default=OUT)
    args = parser.parse_args()
    out = args.out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    digest = lambda path: hashlib.sha256(path.read_bytes()).hexdigest()
    source_sha = digest(SOURCE/'weights.npz')
    annotations_sha = digest(ROOT/'NN/review/annotations.json')
    source_metrics = json.loads((SOURCE/'metrics.json').read_text('utf-8'))
    assert annotations_sha == source_metrics['review_sha256'], 'Annotations changed: reevaluate float model first'
    weights = dict(np.load(SOURCE/'weights.npz'))
    q = quantized_weights(weights)
    vectors = np.load(SOURCE/'verification_vectors.npz')
    reference = np.array([quantized_predict(raw[:int(n)], q) for raw, n in zip(vectors['raw'], vectors['lengths'])])
    np.savez(out/'quantized_weights.npz', **q)
    np.savez(out/'verification_vectors.npz', raw=vectors['raw'], lengths=vectors['lengths'], probabilities=reference)
    export_header(q, vectors['raw'], vectors['lengths'], reference, ROOT/'main/fall_model_data_int8.h')
    print('INT8 header exported; compiling independent float and INT8 C libraries.', flush=True)
    float_lib, int8_lib = compile_library(out, False), compile_library(out, True)
    error = ct.c_float()
    self_test = bool(int8_lib.fall_self_test(ct.byref(error)))
    assert self_test
    vector_prob = predict(int8_lib, [raw[:int(n)] for raw, n in zip(vectors['raw'], vectors['lengths'])])
    reference_error = float(np.abs(vector_prob-reference).max())
    records = assign_splits(load())
    val = class_windows(records, 'validation')
    clips = [clip for k in range(3) for clip in val[k]]
    labels = np.array([k for k in range(3) for clip in val[k]])
    fp, qp = predict(float_lib, clips), predict(int8_lib, clips)
    corrupted = [disconnect(clip, 1701+i*4+trial) for i, clip in enumerate(clips) for trial in range(4)]
    targets = np.repeat(labels, 4)
    fpc, qpc = predict(float_lib, corrupted), predict(int8_lib, corrupted)
    independent = np.array([quantized_predict(clip, q) for clip in clips+corrupted])
    evaluation_reference_error = float(np.abs(np.concatenate((qp, qpc))-independent).max())
    reference_error = max(reference_error, evaluation_reference_error)
    def stress(probabilities):
        nonfall = targets != 1
        return dict(metrics=metrics(targets, probabilities),
            nonfall_argmax_fall=int(((probabilities.argmax(1)==1)&nonfall).sum()),
            nonfall_fall_score_ge_08=int(((probabilities[:, 1]>=.8)&nonfall).sum()))
    full = [i for i, clip in enumerate(clips) if len(clip) == WINDOW]
    float_bytes = sum(v.nbytes for k, v in weights.items() if not k.startswith('velocity.'))
    int8_bytes = sum(v.nbytes for v in q.values())
    stress_float, stress_int8 = stress(fpc), stress(qpc)
    stream = stream_comparison(records, float_lib, int8_lib)
    checks = dict(self_test=self_test, numpy_c_reference=reference_error < 1e-4,
        clean_accuracy_no_decrease=metrics(labels, qp)['accuracy'] >= metrics(labels, fp)['accuracy'],
        short_clip_fall_recall_no_decrease=metrics(labels, qp)['recall'][1] >= metrics(labels, fp)['recall'][1],
        synthetic_nonfall_high_scores_no_increase=stress_int8['nonfall_fall_score_ge_08'] <= stress_float['nonfall_fall_score_ge_08'],
        synthetic_nonfall_argmax_fall_no_increase=stress_int8['nonfall_argmax_fall'] <= stress_float['nonfall_argmax_fall'],
        replay_stable_decisions_unchanged=stream['stable_class_changes'] == 0,
        replay_fall_threshold_bands_unchanged=stream['fall_threshold_band_changes'] == 0,
        source_weights_unchanged=source_sha == digest(SOURCE/'weights.npz'),
        annotations_unchanged=annotations_sha == digest(ROOT/'NN/review/annotations.json'))
    report = dict(method='Symmetric per-output INT8 weights, dynamically quantized INT8 matrix inputs, int32 accumulation; float32 features/biases/LSTM state/nonlinearities.',
        window_frames=WINDOW, source_weights_sha256=source_sha, review_sha256=annotations_sha,
        parameter_storage=dict(float32_bytes=float_bytes, mixed_int8_bytes=int8_bytes,
            reduction_percent=100*(1-int8_bytes/float_bytes), compression_ratio=float_bytes/int8_bytes,
            note='Parameter arrays including per-output scales and float biases; excludes code, self-test vectors, stack and queue.'),
        validation_float=metrics(labels, fp), validation_int8=metrics(labels, qp),
        validation_argmax_changes=int((fp.argmax(1) != qp.argmax(1)).sum()),
        validation_max_probability_change=float(np.abs(fp-qp).max()),
        full_window_validation_int8=metrics(labels[full], qp[full]),
        full_window_validation_fall_support=int((labels[full]==1).sum()),
        dropout_float=stress_float, dropout_int8=stress_int8,
        dropout_argmax_changes=int((fpc.argmax(1) != qpc.argmax(1)).sum()),
        dropout_max_probability_change=float(np.abs(fpc-qpc).max()),
        c_self_test_max_error=error.value, numpy_c_reference_vectors=len(reference),
        numpy_c_reference_max_error=reference_error, streaming=stream,
        numpy_c_evaluation_sequences=len(independent),
        numpy_c_evaluation_max_error=evaluation_reference_error,
        edge_checks=edge_checks(int8_lib), checks=checks, host_acceptance_passed=all(checks.values()),
        host_evaluation_only=True,
        device_benchmark='NN/artifacts/physics_fall_int8/device_benchmark.json (if present; separate board measurement)',
        limitations=['Validation clips are small/correlated and were used in previous checkpoint selection.',
            'No complete 24-frame fall validation window; full-event recall remains unmeasured.',
            'Mixed INT8, not an end-to-end integer neural network.'])
    path = out/'quantization_report.json'
    path.write_text(json.dumps(report, indent=2, ensure_ascii=False)+'\n', encoding='utf-8')
    print(json.dumps(report, indent=2, ensure_ascii=False), flush=True)
    if not all(checks.values()):
        raise SystemExit('INT8 candidate failed host acceptance; keep float firmware.')


if __name__ == '__main__':
    main()
